"""Write docs/data_quality.md from the live database so the numbers can never drift from the code."""
from __future__ import annotations

from pathlib import Path

import duckdb

from mart.checks import run_checks

NONPRODUCT = "select count(*) from fact_lines where line_type not in ('sale', 'return')"


def write_report(con: duckdb.DuckDBPyConnection, path: str | Path) -> None:
    q = lambda s: con.execute(s).fetchone()[0]  # noqa: E731
    raw = q("select count(*) from raw_lines")
    kept = q("select count(*) from fact_lines")
    out = [
        "# Data quality report", "",
        "Generated by `python -m mart.cli build`. Do not edit by hand.", "",
        "## Where every raw row went", "",
        "| Outcome | Rows | Amount (GBP) |", "|---|---:|---:|",
    ]
    for lt, n, amt in con.execute("select line_type, count(*), sum(amount) from fact_lines group by 1 order by 2 desc").fetchall():
        out.append(f"| kept: {lt} | {n:,} | {float(amt):,.0f} |")
    for rr, n, amt in con.execute("select reject_reason, count(*), sum(amount) from quarantine_lines group by 1 order by 2 desc").fetchall():
        out.append(f"| quarantined: {rr} | {n:,} | {float(amt):,.0f} |")
    out += ["", f"Total {raw:,} raw rows = {kept:,} kept + {raw - kept:,} quarantined. Nothing is deleted: quarantined rows stay in `quarantine_lines` with their reason.", "",
            "## What normalization changed", "", "| Problem in the raw file | Count | Fix |", "|---|---:|---|"]
    out += [
        f"| Stock codes written in more than one case or with stray spaces | {q('select count(*) from (select stock_code from stg_lines group by 1 having count(distinct stock_code_raw) > 1)'):,} codes | Trimmed and upper-cased |",
        f"| Descriptions with extra whitespace | {q('select count(*) from stg_lines where description_raw is not null and description_raw <> description_clean'):,} rows | Trimmed and collapsed |",
        f"| Products with conflicting descriptions | {q('select count(*) from dim_product where description_variants > 1'):,} products | One canonical description: the most frequent, latest on a tie |",
        f"| Country labels that were not clean names (EIRE, RSA, USA, Korea, European Community) | {q('select count(*) from line_classified where country_raw <> country'):,} rows | Mapped in `seeds/country_map.csv`, with a region |",
        f"| Customers recorded in more than one country | {q('select count(*) from (select customer_id from line_classified where customer_id is not null group by 1 having count(distinct country_raw) > 1)'):,} customers | Assigned the country with most lines |",
        f"| Lines with no customer id (guest checkouts) | {q('select count(*) from fact_lines where customer_id is null'):,} rows | Kept for revenue, excluded from customer metrics |",
        f"| Non-product lines (postage, fees, discounts, adjustments, bad debt) | {q(NONPRODUCT):,} rows | Typed by `seeds/stock_code_types.csv`, kept out of product revenue |",
        f"| Same-hour order reversals (credit note mirrors a sale within 60 minutes) | {q('select count(*) from fact_lines where is_quick_reversal'):,} lines | Flagged; excluded from the adjusted return rate and product revenue |",
    ]
    out += ["", "## Checks", "", "| Check | Result | What it proves |", "|---|---|---|"]
    for r in run_checks(con):
        status = "pass" if r["passed"] else ("fail" if r["blocking"] else f"info: {int(r['violations'])}")
        out.append(f"| `{r['name']}` | {status} | {r['description']} |")
    out += ["", "A blocking check that fails stops the build.", ""]
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(out))
